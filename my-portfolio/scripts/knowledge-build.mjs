// Compiles knowledge/*.md into api/_lib/knowledge-data.js — the sections the
// chat proxy retrieves from. Run `npm run kb` after editing the markdown
// (`npm run dev` and `npm run build` also run it).
//
// Each "## " heading starts a section. Text is squeezed for tokens: comments,
// markdown syntax and extra whitespace are removed. The output is a plain JS
// module so Vercel bundles it with the function — no file reads at runtime.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'knowledge');
const OUT = join(root, 'api', '_lib', 'knowledge-data.js');

const compact = (text) => text
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\*\*|__|`/g, '')                    // bold / code markers
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')      // [text](url) → text
    .replace(/^\s*[-*]\s+/gm, '')                 // list bullets
    .replace(/\s+/g, ' ')
    .trim();

export function buildKnowledge() {
    if (!existsSync(SRC)) return 0;
    const sections = [];
    for (const file of readdirSync(SRC).filter(f => f.endsWith('.md')).sort()) {
        const raw = readFileSync(join(SRC, file), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
        for (const part of raw.split(/^## /m).slice(1)) {
            const [heading, ...body] = part.split('\n');
            const text = compact(body.join('\n'));
            if (text) sections.push({ title: compact(heading), text });
        }
    }
    const banner = '// GENERATED by scripts/knowledge-build.mjs from knowledge/*.md — edit those, then `npm run kb`.\n';
    writeFileSync(OUT, `${banner}export default ${JSON.stringify(sections, null, 1)};\n`);
    return sections.length;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
    const n = buildKnowledge();
    const chars = JSON.stringify(readFileSync(OUT, 'utf8')).length;
    console.log(`knowledge: ${n} sections → api/_lib/knowledge-data.js (~${Math.round(chars / 4).toLocaleString()} tokens total; only a few are sent per question)`);
}
